import Foundation

struct PinyinExercise: Identifiable {
    let id: String
    let pinyin: String
    let word: String
    let initial: String
    let hint: String
}

enum PinyinLesson {
    static let groups = ["全部音节", "b / d / p / q", "平舌与翘舌", "零声母"]
    static let starterExercises: [PinyinExercise] = [
        .init(id: "ba", pinyin: "bā", word: "八", initial: "b", hint: "b：先闭双唇，轻轻放开，送气弱。"),
        .init(id: "da", pinyin: "dā", word: "搭", initial: "d", hint: "d：舌尖抵住上齿龈再放开，送气弱。"),
        .init(id: "pa", pinyin: "pā", word: "趴", initial: "p", hint: "p：闭唇后送出明显气流，可以用纸巾感受。"),
        .init(id: "qi", pinyin: "qī", word: "七", initial: "q", hint: "q：舌面前部靠近硬腭，送气明显；注意字形右上圆圈。"),
        .init(id: "zhi", pinyin: "zhī", word: "枝", initial: "zh", hint: "zh：舌尖翘起，送气弱。"),
        .init(id: "zi", pinyin: "zī", word: "姿", initial: "z", hint: "z：舌尖靠近上齿背，舌尖不翘起。"),
        .init(id: "chi", pinyin: "chī", word: "吃", initial: "ch", hint: "ch：舌尖翘起，送气明显。"),
        .init(id: "ci", pinyin: "cī", word: "疵", initial: "c", hint: "c：舌尖不翘起，送气明显。"),
        .init(id: "shi", pinyin: "shī", word: "诗", initial: "sh", hint: "sh：舌尖翘起，让气流从窄缝通过。"),
        .init(id: "si", pinyin: "sī", word: "丝", initial: "s", hint: "s：舌尖不翘起，让气流从齿间通过。")
    ]
    static let initials = ["zh", "ch", "sh", "b", "p", "m", "f", "d", "t", "n", "l", "g", "k", "h", "j", "q", "x", "r", "z", "c", "s"]
    static let whole: Set<String> = ["zhi", "chi", "shi", "ri", "zi", "ci", "si", "yi", "wu", "yu", "ye", "yue", "yin", "yun", "yuan", "ying"]
    static func plain(_ text: String) -> String {
        let marked = Array("āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜ")
        let bases = Array("aaaaeeeeiiiioooouuuuüüüü")
        return String(text.lowercased().precomposedStringWithCanonicalMapping.map { char in
            marked.firstIndex(of: char).map { bases[$0] } ?? char
        })
    }
    static func initial(for pinyin: String) -> String {
        let base = plain(pinyin)
        return initials.first(where: { base.hasPrefix($0) }) ?? ""
    }
    static func final(for pinyin: String) -> String {
        let base = plain(pinyin), initial = initial(for: pinyin)
        var final = String(base.dropFirst(initial.count))
        if ["j", "q", "x"].contains(initial), final.hasPrefix("u") {
            final = "ü" + final.dropFirst()
        }
        return final
    }
    static let exercises: [PinyinExercise] = starterExercises + catalog.filter { candidate in
        !starterExercises.contains(where: { $0.pinyin == candidate.pinyin })
    }
    static func items(group: Int) -> [PinyinExercise] {
        switch group {
        case 1: return exercises.filter { ["b", "d", "p", "q"].contains($0.initial) }
        case 2: return exercises.filter { ["zh", "ch", "sh", "z", "c", "s"].contains($0.initial) }
        case 3: return exercises.filter { $0.initial.isEmpty }
        default: return exercises
        }
    }
    static func choices(for item: PinyinExercise, group: Int) -> [PinyinExercise] {
        let pool = items(group: group)
        let close = pool.filter { $0.id != item.id && (plain($0.pinyin) == plain(item.pinyin) || final(for: $0.pinyin) == final(for: item.pinyin)) }
        var choices = Array(close.prefix(5))
        for other in pool where other.id != item.id && !choices.contains(where: { $0.id == other.id }) {
            if choices.count == 5 { break }; choices.append(other)
        }
        choices.insert(item, at: item.pinyin.unicodeScalars.reduce(0) { $0 + Int($1.value) } % (choices.count + 1))
        return choices
    }
    static let initialSounds = ["b":"玻", "p":"坡", "m":"摸", "f":"夫", "d":"德", "t":"特", "n":"讷", "l":"勒", "g":"哥", "k":"科", "h":"喝", "j":"鸡", "q":"七", "x":"西", "zh":"知", "ch":"吃", "sh":"诗", "r":"日", "z":"资", "c":"疵", "s":"丝"]
    static let finalSounds = ["a":"啊", "o":"喔", "e":"鹅", "i":"衣", "u":"乌", "ü":"迂", "ai":"哀", "ei":"诶", "ao":"凹", "ou":"欧", "an":"安", "en":"恩", "ang":"昂", "eng":"鞥", "er":"儿", "ia":"呀", "ie":"耶", "iao":"腰", "iou":"优", "iu":"优", "ian":"烟", "in":"因", "iang":"央", "ing":"英", "ua":"蛙", "uo":"窝", "uai":"歪", "uei":"威", "ui":"威", "uan":"弯", "uen":"温", "un":"温", "uang":"汪", "ueng":"翁", "üe":"约", "üan":"冤", "ün":"晕"]
    static func explanation(for item: PinyinExercise) -> String {
        let base = plain(item.pinyin)
        if whole.contains(base) { return "整体认读：\(item.pinyin)，直接读，不拆拼。" }
        if item.initial.isEmpty { return "零声母音节：\(item.pinyin)，直接读完整音节。" }
        let final = final(for: item.pinyin)
        let suffix = finalSounds[final] == nil ? "；此韵母暂无独立示范音，以完整音节示范。" : ""
        return "\(item.initial) → \(final) → \(item.pinyin)\(suffix)"
    }
    static let wholeSyllables: Set<String> = ["zhi", "chi", "shi", "ri", "zi", "ci", "si", "yi", "wu", "yu", "ye", "yue", "yin", "yun", "yuan", "ying"]
    static func demonstration(for item: PinyinExercise) -> [String] {
        let base = plain(item.pinyin)
        guard !wholeSyllables.contains(base), !item.initial.isEmpty,
              let initialSound = initialSounds[item.initial] else { return [item.word] }
        let final = final(for: item.pinyin)
        if let sound = finalSounds[final] { return [initialSound, sound, item.word] }
        let medials = ["i":"衣", "u":"乌", "ü":"迂"]
        if let first = final.first, let medial = medials[String(first)],
           let rime = finalSounds[String(final.dropFirst())] {
            return [initialSound, medial, rime, item.word]
        }
        // Some finals have no safe single-character Mandarin TTS proxy.
        // Do not spell Latin letters or substitute a different vowel.
        return [item.word]
    }

    static func spellingLabel(for item: PinyinExercise) -> String {
        if wholeSyllables.contains(plain(item.pinyin)) { return "整体认读：" + item.pinyin }
        if item.initial.isEmpty { return "零声母音节：" + item.pinyin }
        if demonstration(for: item).count == 1 { return "暂仅提供合读示范：" + item.pinyin }
        return item.initial + " → " + final(for: item.pinyin) + " → " + item.pinyin
    }
    static let catalog: [PinyinExercise] = catalogRows.split(separator: "\n").compactMap { row in
        let parts = row.split(separator: "|")
        guard parts.count == 2 else { return nil }
        let py = String(parts[0])
        return PinyinExercise(id: "syllable-" + py, pinyin: py, word: String(parts[1]), initial: initial(for: py), hint: "先听示范，再读一次完整音节，注意声调。")
    }

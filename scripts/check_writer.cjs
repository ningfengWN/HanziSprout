const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:680}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const dir=path.resolve(__dirname,'../HanziSprout/Resources');
 await page.goto('file://'+dir+'/writer.html');
 const data=JSON.parse(fs.readFileSync(dir+'/Strokes/今.json','utf8'));
 await page.evaluate(d=>window.start('今',d),data);
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('写好了'),{timeout:20000});
 await page.click('#step');
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('第 1 笔'));
 await page.click('#step');
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('第 2 笔'));
 await page.click('#outline');
 await page.click('#play');await page.click('#pause');
 if(await page.locator('#pause').textContent()!=='继续') throw Error('pause failed');
 await page.screenshot({path:path.resolve('hanzi-iphone.png')});
 await page.click('#pause');
 await page.click('#play');
 await page.click('#step');
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('第 1 笔'));
 await page.setViewportSize({width:1024,height:1100});
 await page.waitForTimeout(400);
 await page.screenshot({path:path.resolve('hanzi-ipad.png')});
 await page.evaluate(()=>window.start('𰻞',null));
 if(!await page.locator('#fallback').isVisible()) throw Error('missing fallback');
 if(errors.length) throw Error(errors.join('\n'));
 console.log('PASS: autoplay, accumulated single strokes, replay, pause/resume, outline, resizing, missing-data fallback; no JS errors');
 await browser.close();
})();
